import { test, expect } from "@playwright/test";
import { exportedPdfText } from "../reports/pdf-text";
import { reportFixture } from "../reports/fixture";

test("downloads a native PDF with the current edits without another source or AI request", async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const report = reportFixture(); let analysisCalls = 0, sourceCalls = 0;
  await page.route("**/api/suggest", route => route.fulfill({ json: { suggestions: [] } }));
  await page.route("**/api/identify", route => route.fulfill({ json: { choices: [{ identity: report.identity, token: "fictional-private-confirmation-token", note: "Fictional PDF fixture." }], sourceFailures: 0 } }));
  await page.route("**/api/records", route => { sourceCalls++; return route.fulfill({ json: report.records }); });
  await page.route("**/api/hazards", route => { sourceCalls++; return route.fulfill({ json: report.flood }); });
  await page.route("**/api/map-config", route => route.fulfill({ status: 503, json: { error: "No fixture map" } }));
  await page.route("**/api/estimates", route => route.fulfill({ status: 503, json: { error: "No live estimates" } }));
  await page.route("**/api/analysis", route => { analysisCalls++; const body = route.request().postDataJSON(); return route.fulfill({ json: { ...report.analysis, revision: body.revision, financeInputKey: JSON.stringify(body.finance) } }); });
  await page.goto("/");
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toHaveCount(0);
  await page.getByLabel("NJ address", { exact: true }).fill(report.identity.address);
  await page.getByRole("button", { name: "Find property", exact: true }).click();
  await page.getByRole("button", { name: "Confirm this property", exact: true }).click();
  await expect(page.getByText("fictional-test-model", { exact: false })).toBeVisible();
  await page.getByRole("tab", { name: "Rental", exact: true }).click();
  await page.getByLabel("Annual property-tax assumption", { exact: true }).fill("7777");
  const requestsBefore = { analysisCalls, sourceCalls };
  let releaseRenderer!: () => void, pendingScripts = 0;
  const rendererGate = new Promise<void>(resolve => { releaseRenderer = resolve; });
  await page.route("**/_next/static/chunks/*.js", async route => { pendingScripts++; await rendererGate; await route.continue(); });
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  await expect.poll(() => pendingScripts).toBeGreaterThan(0);
  await expect(page.getByRole("button", { name: "Preparing PDF…", exact: true })).toBeDisabled();
  await page.getByLabel("Annual property-tax assumption", { exact: true }).fill("8888");
  releaseRenderer();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/^BidWise-10-Example-Street-\d{4}-\d{2}-\d{2}\.pdf$/);
  await download.saveAs(testInfo.outputPath("property-report.pdf"));
  const stream = await download.createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const buffer = Buffer.concat(chunks);
  expect(buffer.subarray(0, 5).toString()).toBe("%PDF-");
  const text = exportedPdfText(buffer);
  for (const value of ["10 Example Street", "$7,777", "Unknown", "AI analysis is outdated", "Record notes & sources", "century is inferred"]) expect(text).toContain(value);
  expect(text).not.toContain("$8,888");
  expect(text).toMatch(/1 \/ \d+/);
  expect(buffer.toString("latin1")).not.toContain("fictional-private-confirmation-token");
  expect({ analysisCalls, sourceCalls }).toEqual(requestsBefore);
  await expect(page.getByRole("button", { name: "Download PDF", exact: true })).toBeEnabled();
  await expect(page.getByLabel("Annual property-tax assumption", { exact: true })).toHaveValue("8888");
});

test("recovers from a failed PDF renderer download while preserving the report and edits", async ({ page }) => {
  const report = reportFixture();
  await page.route("**/api/**", route => {
    const path = new URL(route.request().url()).pathname;
    if (path === "/api/suggest") return route.fulfill({ json: { suggestions: [] } });
    if (path === "/api/identify") return route.fulfill({ json: { choices: [{ identity: report.identity, token: "fictional-token", note: "Fictional fixture." }], sourceFailures: 0 } });
    if (path === "/api/records") return route.fulfill({ json: report.records });
    if (path === "/api/hazards") return route.fulfill({ json: report.flood });
    return route.fulfill({ status: 503, json: { error: "No live model or map in this fixture" } });
  });
  await page.goto("/");
  await page.getByLabel("NJ address", { exact: true }).fill(report.identity.address);
  await page.getByRole("button", { name: "Find property", exact: true }).click();
  await page.getByRole("button", { name: "Confirm this property", exact: true }).click();
  await expect(page.getByText("AI analysis could not be completed.", { exact: false })).toBeVisible();
  await page.getByRole("tab", { name: "Rental", exact: true }).click();
  await page.getByLabel("Annual property-tax assumption", { exact: true }).fill("7777");
  await page.route("**/_next/static/chunks/*.js", route => route.abort("failed"));
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "PDF could not be prepared" })).toBeVisible();
  await expect(page.getByLabel("Annual property-tax assumption", { exact: true })).toHaveValue("7777");
  await page.unroute("**/_next/static/chunks/*.js");
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PDF", exact: true }).click();
  expect((await downloaded).suggestedFilename()).toMatch(/\.pdf$/);
  await expect(page.getByRole("alert").filter({ hasText: "PDF could not be prepared" })).toHaveCount(0);
});
